"""Focused bootstrap/selection checks; no Go commands or scenario execution."""
import copy
import hashlib
import importlib.util
import io
import os
from pathlib import Path
import tempfile
import time
import unittest
from unittest import mock


ROOT = Path(__file__).resolve().parents[2]


def adapter():
    spec = importlib.util.spec_from_file_location(
        "assurance_selection", ROOT / "tools/compatibility/check-selection.py"
    )
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


class FetchTests(unittest.TestCase):
    def test_digest_mismatch_refuses_helper_before_execution(self):
        module = adapter()
        payload = b"raise AssertionError('unverified code executed')"
        with self.assertRaisesRegex(ValueError, "digest mismatch"):
            module.fetch_verified(
                module.HELPER_URL, "0" * 64, 1024,
                open_url=lambda *_args, **_kwargs: io.BytesIO(payload),
            )

    def test_fetch_returns_only_verified_bounded_bytes(self):
        module = adapter()
        payload = b"immutable input\n"
        actual = module.fetch_verified(
            module.HELPER_URL, hashlib.sha256(payload).hexdigest(), len(payload),
            open_url=lambda *_args, **_kwargs: io.BytesIO(payload),
        )
        self.assertEqual(actual, payload)

    def test_oversize_is_fatal_even_with_a_matching_digest(self):
        module = adapter()
        payload = b"x" * 65
        with self.assertRaisesRegex(ValueError, "byte budget"):
            module.fetch_verified(
                module.HELPER_URL, hashlib.sha256(payload).hexdigest(), 64,
                open_url=lambda *_args, **_kwargs: io.BytesIO(payload),
            )

    def test_transport_failure_is_not_a_cached_or_latest_fallback(self):
        module = adapter()

        def unavailable(*_args, **_kwargs):
            raise OSError("unavailable")

        with self.assertRaisesRegex(OSError, "unavailable"):
            module.fetch_verified(module.HELPER_URL, "0" * 64, 64, open_url=unavailable)

    def test_duplicate_selection_keys_refuse(self):
        with self.assertRaisesRegex(ValueError, "duplicate JSON key"):
            adapter().decode_json(b'{"format":"first","format":"second"}')

    def test_expired_deadline_refuses_before_network_access(self):
        def unexpected(*_args, **_kwargs):
            self.fail("expired bootstrap deadline attempted network access")

        with self.assertRaisesRegex(TimeoutError, "time budget"):
            adapter().fetch_verified(
                adapter().HELPER_URL, "0" * 64, 64,
                open_url=unexpected, deadline=time.monotonic() - 1,
            )

    def test_unknown_cli_mode_refuses_without_downloading(self):
        module = adapter()
        with mock.patch.object(module, "load_inputs", side_effect=AssertionError("downloaded")):
            for arguments in (["--write", "extra"], ["--force"], ["--write", "--write"]):
                with self.subTest(arguments=arguments), self.assertRaisesRegex(ValueError, "usage"):
                    module.main(arguments)

    def test_unowned_input_name_refuses(self):
        with self.assertRaisesRegex(ValueError, "unknown scenario input"):
            adapter().read_owned("../../foreign", 1024)


class SelectionTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.module = adapter()
        # These are real immutable published inputs, verified before execution.
        # Fetch once; all refusal cases then use the same in-memory inputs.
        cls.inputs = cls.module.load_inputs()
        directory = ROOT / "scenarios/compatibility-consumer"
        cls.selection = cls.module.decode_json((directory / "selection.json").read_bytes())
        cls.go_mod = (directory / "go.mod").read_text()
        cls.imports = (directory / "consumer_test.go").read_text()

    def check(self, *, selection=None, go_mod=None, imports=None):
        return self.module.validate_selection(
            self.inputs,
            self.selection if selection is None else selection,
            self.go_mod if go_mod is None else go_mod,
            self.imports if imports is None else imports,
        )

    def test_actual_relocated_scenario_matches_the_published_generic_renderer(self):
        self.assertEqual(self.check(), 167)

    def test_generated_header_names_the_actual_owner_entrypoint(self):
        self.assertTrue(self.imports.startswith(
            "// Code generated by ../../tools/compatibility/check-selection.py; DO NOT EDIT.\n\n"
        ))
        self.assertEqual(self.check(), 167)

    def test_manual_or_stale_generator_headers_refuse(self):
        body = self.imports.split("\n\n", 1)[1]
        for prefix in ("", "// Code generated by handwritten.py; DO NOT EDIT.\n\n",
                       "// manual header\n"):
            with self.subTest(prefix=prefix):
                with self.assertRaisesRegex(ValueError, "consumer_test.go"):
                    self.check(imports=prefix + body)

    def test_write_uses_real_renderer_twice_and_preserves_all_other_inputs(self):
        selected, catalogs = self.inputs[0].current_consumer_inputs(
            self.inputs[1], self.inputs[2], self.selection, verify_public=False,
        )
        _, expected = self.inputs[0].render_clean_consumer(
            selected, catalogs, generator_path="../../tools/compatibility/check-selection.py",
        )
        frozen_inputs = copy.deepcopy(self.inputs[1:])
        legacy_imports = expected.split("\n\n", 1)[1]
        tracked = ROOT / "scenarios/compatibility-consumer"
        # At adoption only the real generated header may change the old import bytes.
        tracked_imports = (tracked / "consumer_test.go").read_text()
        if tracked_imports.startswith("// Code generated"):
            tracked_imports = tracked_imports.split("\n\n", 1)[1]
        self.assertEqual(legacy_imports, tracked_imports)
        with tempfile.TemporaryDirectory(prefix="assurance-render-test-") as task:
            root = Path(task)
            directory = root / "scenarios/compatibility-consumer"
            directory.mkdir(parents=True)
            for name in ("go.mod", "go.sum", "selection.json"):
                (directory / name).write_bytes((tracked / name).read_bytes())
            (directory / "consumer_test.go").write_text(legacy_imports)
            frozen = {p: p.read_bytes() for p in directory.iterdir()
                      if p.name != "consumer_test.go"}
            with mock.patch.object(self.module, "ROOT", root):
                for _ in range(2):
                    self.assertEqual(self.module.maintain_scenario(self.inputs, write=True), 167)
                    self.assertEqual((directory / "consumer_test.go").read_text(), expected)
                    self.assertEqual({p: p.read_bytes() for p in frozen}, frozen)
                self.assertEqual(self.module.maintain_scenario(self.inputs), 167)
                self.assertEqual(self.inputs[1:], frozen_inputs)

    def test_write_refuses_dependency_drift_without_mutating_source(self):
        with tempfile.TemporaryDirectory(prefix="assurance-refusal-test-") as task:
            root = Path(task)
            directory = root / "scenarios/compatibility-consumer"
            directory.mkdir(parents=True)
            (directory / "selection.json").write_bytes(
                (ROOT / "scenarios/compatibility-consumer/selection.json").read_bytes())
            (directory / "go.mod").write_text(self.go_mod.replace(
                "go-adaptive-throttle v1.0.1", "go-adaptive-throttle v1.0.2", 1))
            target = directory / "consumer_test.go"
            target.write_text("untouched source\n")
            with mock.patch.object(self.module, "ROOT", root):
                with self.assertRaisesRegex(ValueError, "go.mod"):
                    self.module.maintain_scenario(self.inputs, write=True)
            self.assertEqual(target.read_text(), "untouched source\n")

    def test_unsafe_owned_paths_refuse_before_read_or_write(self):
        tracked = ROOT / "scenarios/compatibility-consumer"
        for unsafe in ("file-symlink", "directory-symlink", "hard-link", "oversized", "missing"):
            with self.subTest(unsafe=unsafe), tempfile.TemporaryDirectory(
                prefix="assurance-owned-test-"
            ) as task:
                root = Path(task)
                directory = root / "scenarios/compatibility-consumer"
                directory.mkdir(parents=True)
                for name in ("selection.json", "go.mod"):
                    (directory / name).write_bytes((tracked / name).read_bytes())
                outside = root / "outside.go"
                outside.write_text("untouched outside\n")
                target = directory / "consumer_test.go"
                if unsafe == "file-symlink":
                    target.symlink_to(outside)
                elif unsafe == "hard-link":
                    os.link(outside, target)
                elif unsafe == "oversized":
                    target.write_bytes(b"x" * (1024 * 1024 + 1))
                elif unsafe == "directory-symlink":
                    directory.rename(root / "original")
                    directory.symlink_to(root / "original", target_is_directory=True)
                with mock.patch.object(self.module, "ROOT", root):
                    with self.assertRaises((ValueError, OSError)):
                        self.module.maintain_scenario(self.inputs, write=True)
                    with self.assertRaises((ValueError, OSError)):
                        self.module.maintain_scenario(self.inputs)
                self.assertEqual(outside.read_text(), "untouched outside\n")

    def test_old_tools_module_identity_refuses(self):
        changed = self.go_mod.replace(self.module.ASSURANCE_HEADER, self.module.TOOLS_HEADER, 1)
        with self.assertRaisesRegex(ValueError, "go.mod"):
            self.check(go_mod=changed)

    def test_changed_direct_dependency_refuses(self):
        changed = self.go_mod.replace("go-adaptive-throttle v1.0.1", "go-adaptive-throttle v1.0.2", 1)
        self.assertNotEqual(changed, self.go_mod)
        with self.assertRaisesRegex(ValueError, "go.mod"):
            self.check(go_mod=changed)

    def test_changed_import_inventory_refuses(self):
        with self.assertRaisesRegex(ValueError, "consumer_test.go"):
            self.check(imports=self.imports + "// stale import inventory\n")

    def test_unknown_replacement_family_refuses_in_actual_generic_policy(self):
        changed = copy.deepcopy(self.selection)
        changed["replacements"][0]["module_path"] = "github.com/faustbrian/go-unrelated/v2"
        with self.assertRaisesRegex(ValueError, "module family"):
            self.check(selection=changed)

    def test_duplicate_replacement_refuses_in_actual_generic_policy(self):
        changed = copy.deepcopy(self.selection)
        changed["replacements"].append(copy.deepcopy(changed["replacements"][0]))
        with self.assertRaisesRegex(ValueError, "duplicated"):
            self.check(selection=changed)


if __name__ == "__main__":
    unittest.main()
